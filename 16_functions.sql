# Functions
-- SQL FUNCTIONS are built-in commands that perform an operation
-- on data and return a result.
-- They are mainly used to calculate, modify, or work with data.

-- Common functions:
-- COUNT()  → counts rows
-- SUM()    → adds numeric values
-- AVG()    → calculates average
-- MAX()    → finds the highest value
-- MIN()    → finds the lowest value
--
-- Example:
SELECT COUNT(*) FROM players;